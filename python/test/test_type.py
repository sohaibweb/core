"""
type()  Built-in function that returns the type of an object or creates a new type object.

all data types in Python is object

"""
int = 1
print(int)
print(type(int)) # integer
float = 1.0
print(float)
print(type(float)) # floating point number
str = "Hello"
print(str)
print(type(str)) # string
list = [1, 2, 3]
print(list)
print(type(list)) # list
tuple = (1, 2, 3)
print(tuple)
print(type(tuple)) # tuple
dict = {"one": 1, "two": 2, "three": 3}
print(dict)
print(type(dict)) # dictionary
set = {2 == 2}
print(set)
print(type(set)) # set
set = {2 == 3}
print(set)
print(type(set)) # set